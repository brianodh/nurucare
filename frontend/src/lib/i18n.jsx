const LanguageContext = createContext();

export const LanguageProvider = ({ children }) => {
  const [lang, setLang] = useState(localStorage.getItem('nurucare_lang') || 'en');

  // Update localStorage when language changes
  const updateLang = (newLang) => {
    setLang(newLang);
    localStorage.setItem('nurucare_lang', newLang);
  };

  const t = (key) => {
    const value = translations[lang]?.[key];
    if (value === undefined && import.meta.env.DEV) {
      console.warn(`[i18n] Missing translation key: "${key}" (lang: ${lang})`);
    }
    return value ?? key;
  };

  const value = {
    lang,
    setLang: updateLang,
    t,
  };

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLang = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLang must be used within a LanguageProvider');
  }
  return context;
};
